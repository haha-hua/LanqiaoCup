/*
 * 用途：list（双向链表）与数组模拟链表（静态链表）的实现与应用
 * 时间复杂度：访问 O(n)，中间插入/删除 O(1)（已定位）
 * 常用方法：push_back, push_front, pop_back, pop_front, insert, erase, begin, end
 * 输入：演示数据
 * 输出：链表操作结果
 */
#include<iostream>
#include<list>

using namespace std;


int main()
{
    //初始化
    list<int> lst;  //默认构造函数，创建一个空的list
    
    //增加
    lst.push_back(1);  //在末尾添加元素1
    lst.push_front(0); //在开头添加元素0，lst现在是{0,1}
    lst.insert(++lst.begin(), 5); //在第二个位置插入元素5，lst现在是{0,5,1}

    //删除
    lst.pop_back(); //删除末尾元素，lst现在是{0,5}
    lst.pop_front(); //删除开头元素，lst现在是{5}
    lst.erase(lst.begin()); //删除第一个元素，lst现在是空的{}

    //查询
    *lst.begin(); //访问第一个元素，前提是list不为空
    lst.size(); //返回元素个数
    lst.empty(); //判断是否为空

    //用数组模拟链表
    const int N = 100005;
    int L[N] = {},R[N] = {}; //L[i]表示第i个元素的前一个元素，R[i]表示第i个元素的后一个元素,
    int w[N] = {}; //存储元素的值

    for(int i = 1; i <= 5; ++i) //初始化链表，元素1到5依次连接
    {
        L[i] = i - 1;
        R[i] = i + 1;
    }
    L[1] = 0; //第一个元素的前一个元素是0，表示没有了
    R[5] = 0; //最后一个元素的后一个元素是0，表示没有了

    //在第3个元素后面插入元素6
    int idx = 6; //新元素的索引
    w[idx] = 6; //新元素的值
    L[idx] = 3; //新元素的前一个元素是3
    R[idx] = R[3]; //新元素的后一个元素是3的后一个元素
    L[R[3]] = idx; //3的后一个元素的前一个元素是新元素
    R[3] = idx; //3的后一个元素是新元素

    //删除第4个元素
    L[R[4]] = L[4]; //4的后一个元素的前一个元素是4的前一个元素
    R[L[4]] = R[4]; //4的前一个元素的后一个元素是4的后一个元素
    L[4] = 0; //4的前一个元素设为0
    R[4] = 0; //4的后一个元素设为0

    //遍历链表
    for(int i = R[0]; i != 0; i = R[i]) //从第一个元素开始，沿着右指针遍历，直到遇到0
    {
        cout << w[i] << " "; //输出当前元素的值
    }

    return 0;
}